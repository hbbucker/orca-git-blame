import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertAsarIntegrityDisabled } from './fuses.mjs';
import { patchBuffer } from './patch-app.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const STATE = process.env.ORCA_GIT_BLAME_HOME ?? join(homedir(), '.local/share/orca-git-blame');
const BIN_DIR = join(homedir(), '.local/bin');
const LAUNCHER = join(BIN_DIR, 'orca-blame');
const DESKTOP = join(homedir(), '.local/share/applications/orca-git-blame.desktop');
const CONFIG = join(STATE, 'config.json');
const KEEP_BUILDS = 2;

function loadConfig() {
  return existsSync(CONFIG) ? JSON.parse(readFileSync(CONFIG, 'utf8')) : {};
}

function resolveAppImage(args, config) {
  const candidate = args.appimage ?? process.env.ORCA_APPIMAGE ?? config.appimage;
  if (!candidate) throw new Error('missing Orca AppImage: npm run patch -- --appimage ~/Apps/orca-linux.AppImage');
  const path = resolve(candidate.replace(/^~(?=\/)/, homedir()));
  if (!statSync(path).isFile()) throw new Error(`${path} is not a file`);
  return path;
}

export function stampOf(appimage) {
  const s = statSync(appimage);
  // invariant: mesmo formato do `stat -c '%s-%Y'` do launcher (tamanho-mtime em segundos).
  return `${s.size}-${Math.trunc(s.mtimeMs / 1000)}`;
}

function extract(appimage, into) {
  rmSync(into, { recursive: true, force: true });
  mkdirSync(into, { recursive: true });
  const r = spawnSync(appimage, ['--appimage-extract'], { cwd: into, stdio: 'ignore' });
  const root = join(into, 'squashfs-root');
  if (r.status !== 0 || !existsSync(join(root, 'resources/app.asar'))) {
    throw new Error(`failed to extract ${appimage} (status ${r.status})`);
  }
  return root;
}

function patchAsar(asarPath) {
  const { buffer, version, preloads, i18nChunks } = patchBuffer(readFileSync(asarPath));
  writeFileSync(`${asarPath}.tmp`, buffer);
  renameSync(`${asarPath}.tmp`, asarPath);
  return { version, preloads, i18nChunks };
}

function pointCurrent(target) {
  const link = join(STATE, 'current');
  const tmp = `${link}.tmp`;
  rmSync(tmp, { force: true });
  symlinkSync(target, tmp);
  renameSync(tmp, link);
}

// hazard: não apaga o build anterior ao atual — uma instância patcheada ainda aberta pode estar rodando dele.
function pruneBuilds(current) {
  const builds = join(STATE, 'builds');
  const dirs = readdirSync(builds)
    .filter((d) => !d.startsWith('tmp-'))
    .map((d) => ({ d, t: statSync(join(builds, d)).mtimeMs }))
    .sort((a, b) => b.t - a.t);
  for (const { d } of dirs.slice(KEEP_BUILDS)) {
    if (join(builds, d) !== current) rmSync(join(builds, d), { recursive: true, force: true });
  }
}

const sq = (value) => `'${String(value).replaceAll("'", `'\\''`)}'`;

// hazard: nada aqui pode depender do Node gravado no install (ex.: versão do nvm removida); o caminho do AppImage vai literal no script para o fallback sempre abrir o Orca original.
export function launcherScript({ state, appimage, nodePath, installScript }) {
  return `#!/usr/bin/env bash
# generated by orca-git-blame/lib/linux.mjs — do not edit; run "npm run patch" in the repo to regenerate.
set -uo pipefail
STATE=${sq(state)}
APPIMAGE_PATH=${sq(appimage)}
stamp=$(stat -c '%s-%Y' "$APPIMAGE_PATH" 2>/dev/null || true)
saved=$(cat "$STATE/stamp" 2>/dev/null || true)
if [[ -z "$stamp" || "$stamp" != "$saved" || ! -x "$STATE/current/AppRun" ]]; then
  if ! ORCA_GIT_BLAME_HOME="$STATE" ${sq(nodePath)} ${sq(installScript)} --quiet >>"$STATE/install.log" 2>&1; then
    command -v notify-send >/dev/null && notify-send "Orca Git Blame" "Inline git blame could not be applied; opening the original Orca. See $STATE/install.log"
    exec "$APPIMAGE_PATH" "$@"
  fi
fi
# why: APPIMAGE aponta o auto-update do Orca para o AppImage original; na próxima abertura o stamp muda e o patch é refeito.
APPIMAGE="$APPIMAGE_PATH" exec "$STATE/current/AppRun" "$@"
`;
}

function writeLauncher(appimage) {
  mkdirSync(BIN_DIR, { recursive: true });
  writeFileSync(
    LAUNCHER,
    launcherScript({ state: STATE, appimage, nodePath: process.execPath, installScript: join(REPO, 'scripts/install.mjs') }),
  );
  chmodSync(LAUNCHER, 0o755);
}

function writeDesktop() {
  mkdirSync(dirname(DESKTOP), { recursive: true });
  writeFileSync(
    DESKTOP,
    `[Desktop Entry]
Type=Application
Name=Orca (Git Blame)
Comment=Orca with inline git blame on the cursor line
Exec=${LAUNCHER} %U
Icon=${join(STATE, 'current/usr/share/icons/hicolor/512x512/apps/orca-ide.png')}
Terminal=false
Categories=Development;IDE;
`,
  );
}

export function install(args, log) {
  const config = loadConfig();
  const appimage = resolveAppImage(args, config);
  const stamp = stampOf(appimage);
  mkdirSync(join(STATE, 'builds'), { recursive: true });

  const work = join(STATE, 'builds', `tmp-${process.pid}`);
  log(`extracting ${appimage}...`);
  const root = extract(appimage, work);
  try {
    assertAsarIntegrityDisabled(join(root, 'orca-ide'));
    const { version, preloads, i18nChunks } = patchAsar(join(root, 'resources/app.asar'));
    log(`Orca ${version}: patch applied (preloads: ${preloads.join(', ')})`);
    if (i18nChunks.length === 0) log('warning: Orca i18n instance not found; blame text will follow the system language.');
    if (args.check) {
      log('--check: patch is compatible; nothing was installed.');
      return;
    }
    const final = join(STATE, 'builds', `${version}-${Date.now()}`);
    renameSync(root, final);
    pointCurrent(final);
    writeFileSync(CONFIG, JSON.stringify({ ...config, appimage }, null, 2));
    writeFileSync(join(STATE, 'stamp'), stamp);
    writeLauncher(appimage);
    writeDesktop();
    pruneBuilds(final);
    log(`installed at ${final}\nlaunch with: ${LAUNCHER}  (or "Orca (Git Blame)" in the app menu)`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

export function uninstall(log) {
  for (const path of [LAUNCHER, DESKTOP, STATE]) {
    rmSync(path, { recursive: true, force: true });
    log(`removed: ${path}`);
  }
  log('The original Orca AppImage was not touched.');
}
