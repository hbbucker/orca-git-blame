import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, win32 } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readArchive } from './asar.mjs';
import { assertAsarIntegrityDisabled } from './fuses.mjs';
import { patchBuffer, patchId, patchState } from './patch-app.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function paths(env = process.env) {
  const localAppData = env.LOCALAPPDATA ?? join(env.USERPROFILE ?? '', 'AppData', 'Local');
  const appData = env.APPDATA ?? join(env.USERPROFILE ?? '', 'AppData', 'Roaming');
  const state = env.ORCA_GIT_BLAME_HOME ?? join(localAppData, 'orca-git-blame');
  return {
    state,
    config: join(state, 'config.json'),
    stamp: join(state, 'stamp'),
    log: join(state, 'install.log'),
    launcher: join(state, 'orca-blame.vbs'),
    shortcut: join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Orca (Git Blame).lnk'),
    // why: o NSIS do Orca é oneClick por usuário; o electron-builder usa então o nome do pacote ("orca") como pasta em %LOCALAPPDATA%\Programs.
    defaultInstallDirs: [join(localAppData, 'Programs', 'orca'), join(localAppData, 'Programs', 'Orca')],
  };
}

function loadConfig(p) {
  return existsSync(p.config) ? JSON.parse(readFileSync(p.config, 'utf8')) : {};
}

export function resolveInstallDir(args, config, p, env = process.env) {
  const candidates = [args.installDir, env.ORCA_INSTALL_DIR, config.installDir, ...p.defaultInstallDirs].filter(Boolean);
  const found = candidates.find((dir) => existsSync(join(dir, 'Orca.exe')) && existsSync(join(dir, 'resources', 'app.asar')));
  if (!found) {
    throw new Error(`Orca install not found (tried: ${candidates.join(', ')}); pass --install-dir <folder containing Orca.exe>`);
  }
  return resolve(found);
}

function stampOf(asarPath) {
  const s = statSync(asarPath);
  return `${patchId()}:${s.size}-${Math.trunc(s.mtimeMs)}`;
}

// invariant: app.asar.orig sempre guarda um asar NÃO patcheado; é atualizado sempre que o Orca instala uma versão nova por cima.
export function ensurePatched({ installDir, check = false }, log) {
  const asarPath = join(installDir, 'resources', 'app.asar');
  const origPath = `${asarPath}.orig`;
  const current = readFileSync(asarPath);
  const state = patchState(readArchive(current));

  if (state.patched && state.patchId === patchId()) {
    log(`Orca ${state.version}: already patched.`);
    return { changed: false, version: state.version };
  }

  let original = current;
  if (state.patched) {
    if (!existsSync(origPath)) throw new Error(`${asarPath} is patched by another version and ${origPath} is missing`);
    original = readFileSync(origPath);
    if (patchState(readArchive(original)).patched) throw new Error(`${origPath} is not an original app.asar`);
  }

  assertAsarIntegrityDisabled(join(installDir, 'Orca.exe'));
  const { buffer, version, preloads, i18nChunks } = patchBuffer(original);
  log(`Orca ${version}: patch applied (preloads: ${preloads.join(', ')})`);
  if (i18nChunks.length === 0) log('warning: Orca i18n instance not found; blame text will follow the system language.');
  if (check) {
    log('--check: patch is compatible; nothing was installed.');
    return { changed: false, version };
  }

  if (!state.patched) copyFileSync(asarPath, origPath);
  const tmp = `${asarPath}.orca-git-blame.tmp`;
  writeFileSync(tmp, buffer);
  try {
    renameSync(tmp, asarPath);
  } catch (error) {
    rmSync(tmp, { force: true });
    // hazard: com o Orca aberto o Windows trava o app.asar; o patch fica para a próxima abertura pelo atalho.
    if (['EBUSY', 'EPERM', 'EACCES'].includes(error.code)) {
      throw new Error(`app.asar is in use (${error.code}); close Orca completely and launch it again`);
    }
    throw error;
  }
  return { changed: true, version };
}

const vbsString = (value) => `"${String(value).replaceAll('"', '""')}"`;
// why: cmd /c remove a primeira e a última aspa da linha quando há mais de duas; o par externo protege as aspas dos caminhos.

export function launcherScript({ nodePath, installScript, state, orcaExe }) {
  return `' generated by orca-git-blame/lib/windows.mjs - do not edit; run "npm run patch" in the repo to regenerate.
Option Explicit
Dim sh, args, i, rc
Set sh = CreateObject("WScript.Shell")
sh.Environment("Process")("ORCA_GIT_BLAME_HOME") = ${vbsString(state)}
rc = sh.Run(${vbsString(`cmd /c ""${nodePath}" "${installScript}" --ensure --quiet >> "${win32.join(state, 'install.log')}" 2>&1"`)}, 0, True)
args = ""
For i = 0 To WScript.Arguments.Count - 1
  args = args & " """ & WScript.Arguments(i) & """"
Next
sh.Run """" & ${vbsString(orcaExe)} & """" & args, 1, False
If rc <> 0 Then
  sh.Popup "Inline git blame could not be applied; Orca opened without it. See " & ${vbsString(win32.join(state, 'install.log'))}, 10, "Orca Git Blame", 48
End If
`;
}

function createShortcut({ shortcut, launcher, orcaExe }) {
  mkdirSync(dirname(shortcut), { recursive: true });
  const ps = (value) => `'${String(value).replaceAll("'", "''")}'`;
  const command = [
    `$s = (New-Object -ComObject WScript.Shell).CreateShortcut(${ps(shortcut)})`,
    `$s.TargetPath = ${ps(join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'wscript.exe'))}`,
    `$s.Arguments = ${ps(`"${launcher}"`)}`,
    `$s.IconLocation = ${ps(`${orcaExe},0`)}`,
    `$s.Description = 'Orca with inline git blame'`,
    '$s.Save()',
  ].join('; ');
  const r = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', command], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`failed to create Start Menu shortcut (status ${r.status})`);
}

export function install(args, log, env = process.env) {
  const p = paths(env);
  const config = loadConfig(p);
  const installDir = resolveInstallDir(args, config, p, env);
  const asarPath = join(installDir, 'resources', 'app.asar');

  // why: o launcher roda isso a cada abertura; comparar o stamp evita ler 120 MB de asar quando nada mudou.
  if (args.ensure && existsSync(p.stamp) && readFileSync(p.stamp, 'utf8') === stampOf(asarPath)) return;

  ensurePatched({ installDir, check: args.check }, log);
  if (args.check) return;

  mkdirSync(p.state, { recursive: true });
  writeFileSync(p.config, JSON.stringify({ ...config, installDir }, null, 2));
  writeFileSync(p.stamp, stampOf(asarPath));
  if (args.ensure) return;

  const orcaExe = join(installDir, 'Orca.exe');
  writeFileSync(
    p.launcher,
    launcherScript({ nodePath: process.execPath, installScript: join(REPO, 'scripts', 'install.mjs'), state: p.state, orcaExe }),
  );
  if (!args.skipShortcut) createShortcut({ shortcut: p.shortcut, launcher: p.launcher, orcaExe });
  log(`patched ${asarPath}\nlaunch with the Start Menu shortcut "Orca (Git Blame)" (it re-applies the patch after Orca updates).`);
}

export function uninstall(log, env = process.env) {
  const p = paths(env);
  const config = loadConfig(p);
  const installDir = config.installDir;
  if (installDir) {
    const asarPath = join(installDir, 'resources', 'app.asar');
    const origPath = `${asarPath}.orig`;
    const patched = existsSync(asarPath) && patchState(readArchive(readFileSync(asarPath))).patched;
    // invariant: nunca apagar atalho e estado deixando um Orca patcheado sem como restaurar; reinstalar o Orca é o único caminho então.
    if (patched && !existsSync(origPath)) {
      throw new Error(`${asarPath} is patched but ${origPath} is missing; reinstall Orca to restore it, then run "npm run unpatch" again`);
    }
    if (patched) {
      renameSync(origPath, asarPath);
      log(`restored original ${asarPath}`);
    } else {
      rmSync(origPath, { force: true });
    }
  }
  for (const path of [p.shortcut, p.state]) {
    rmSync(path, { recursive: true, force: true });
    log(`removed: ${path}`);
  }
}
